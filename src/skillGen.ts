/**
 * Skill generation (v1.20.0) — turn repeated procedural experience into
 * reusable agent skill definitions.
 *
 * Procedural lessons ("when touching Terraform, run fmt → validate → checkov")
 * are rendered into one generated markdown file of skill blocks, each citing
 * the sessions it was learned from and carrying the lesson's confidence.
 * GHCP-MEM GENERATES the definitions; it never executes them — execution
 * belongs to the agent harness that consumes the file.
 *
 * The output file is a generated memory artifact: it is listed in
 * GENERATED_MEMORY_FILES (capture exclusion) and scanned by the integrity
 * checker like every other generated surface.
 *
 * Pure module — no vscode imports; callers do the file I/O.
 */
import { Lesson } from './lessons';

export const SKILLS_FILE = '.github/skills/ghcp-mem.skills.md';
const MAX_SKILLS = 50;

/** Heuristic step extraction: numbered/bulleted fragments, else then-sequences. */
export function extractSteps(text: string): string[] {
  const clean = (parts: string[]): string[] =>
    parts
      .map((part) => part.trim().replace(/[.;,\s]+$/, ''))
      .filter((part) => part.length >= 3 && part.length <= 160)
      .slice(0, 12);
  const markerRe = /(?:^|\s)(?:\d+[.)]|[-*•])\s+/g;
  const markers = text.match(markerRe)?.length ?? 0;
  if (markers >= 2) {
    const parts = text.split(markerRe).filter((part) => part.trim());
    // Everything before the first marker is preamble, not a step.
    const steps = clean(parts.slice(parts.length - markers));
    if (steps.length >= 2) return steps;
  }
  const sequenced = clean(text.split(/\bthen\b|→|;/i));
  return sequenced.length >= 2 ? sequenced : [];
}

export function skillName(lesson: Lesson): string {
  const slug = lesson.text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .split('-')
    .slice(0, 6)
    .join('-');
  return slug || `lesson-${lesson.id.slice(0, 8)}`;
}

/** Render one procedural lesson as a skill block; undefined when it has no steps. */
export function renderSkill(lesson: Lesson): string | undefined {
  if (lesson.kind !== 'procedural') return undefined;
  const steps = extractSteps(lesson.text);
  if (steps.length < 2) return undefined;
  const lines = [
    `## skill: ${skillName(lesson)}`,
    '',
    `> ${lesson.text.trim()}`,
    '',
    ...(lesson.tags.length ? [`- triggers: ${lesson.tags.slice(0, 6).join(', ')}`] : []),
    `- confidence: ${lesson.confidence.toFixed(2)} (support: ${lesson.supportCount} session${lesson.supportCount === 1 ? '' : 's'})`,
    `- learned_from: ${lesson.sources
      .slice(0, 8)
      .map((id) => id.slice(0, 8))
      .join(', ')}`,
    '',
    '### steps',
    '',
    ...steps.map((step, index) => `${index + 1}. ${step}`),
  ];
  return lines.join('\n');
}

/** Render the complete generated skills file from the current lessons. */
export function renderSkillsFile(lessons: readonly Lesson[], now = Date.now()): string {
  const blocks = lessons
    .filter((lesson) => lesson.kind === 'procedural')
    .sort((a, b) => b.confidence - a.confidence || b.supportCount - a.supportCount)
    .map(renderSkill)
    .filter((block): block is string => !!block)
    .slice(0, MAX_SKILLS);
  const header = [
    '<!-- Generated by GHCP-MEM from procedural lessons. Do not hand-edit; regenerate',
    '     with "GHCP-MEM: Export Learned Skills". GHCP-MEM generates these definitions',
    '     and never executes them. -->',
    `# Learned skills (${blocks.length})`,
    '',
    `_Generated ${new Date(now).toISOString()} from consolidated procedural memory. Each skill cites the sessions it was learned from; confidence comes from support breadth, not from independent verification._`,
    '',
  ].join('\n');
  return blocks.length
    ? `${header}\n${blocks.join('\n\n---\n\n')}\n`
    : `${header}\n_No procedural lessons have enough structure to render as skills yet._\n`;
}
