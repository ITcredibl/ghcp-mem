import { test } from 'node:test';
import assert from 'node:assert/strict';
import { extractSteps, renderSkill, renderSkillsFile, skillName } from '../skillGen';
import { Lesson } from '../lessons';

function mkLesson(o: Partial<Lesson> = {}): Lesson {
  return {
    id: o.id ?? Math.random().toString(36).slice(2),
    kind: o.kind ?? 'procedural',
    text:
      o.text ??
      'When modifying Terraform: 1. run terraform fmt -check 2. run terraform validate 3. run checkov -d .',
    tags: o.tags ?? ['terraform'],
    sources: o.sources ?? ['991af000', '342bc000'],
    supportCount: o.supportCount ?? 3,
    confidence: o.confidence ?? 0.96,
    createdAt: 1,
    updatedAt: 2,
    ...o,
  };
}

test('skillGen: extracts numbered steps and then-sequences', () => {
  assert.deepEqual(extractSteps('1. run fmt 2. run validate 3. run checkov'), [
    'run fmt',
    'run validate',
    'run checkov',
  ]);
  assert.deepEqual(extractSteps('build the image then push it then deploy'), [
    'build the image',
    'push it',
    'deploy',
  ]);
  assert.deepEqual(extractSteps('just one unstructured observation'), []);
});

test('skillGen: renders procedural lessons only, with citations and confidence', () => {
  const block = renderSkill(mkLesson());
  assert.ok(block);
  assert.match(block, /## skill: /);
  assert.match(block, /confidence: 0\.96 \(support: 3 sessions\)/);
  assert.match(block, /learned_from: 991af000, 342bc000/);
  assert.match(block, /1\. run terraform fmt -check/);
  assert.equal(renderSkill(mkLesson({ kind: 'semantic' })), undefined);
  assert.equal(renderSkill(mkLesson({ text: 'no steps here at all' })), undefined);
});

test('skillGen: skill names are stable slugs', () => {
  assert.equal(
    skillName(mkLesson({ text: 'When modifying Terraform, validate everything first' })),
    'when-modifying-terraform-validate-everything-first',
  );
});

test('skillGen: file render carries the generated/never-executed notice', () => {
  const file = renderSkillsFile([mkLesson(), mkLesson({ kind: 'semantic' })], 1700000000000);
  assert.match(file, /Generated by GHCP-MEM/);
  assert.match(file, /never executes them/);
  assert.match(file, /# Learned skills \(1\)/);
  assert.match(file, /2023-11-14/);
});

test('skillGen: empty procedural memory yields an honest empty file', () => {
  const file = renderSkillsFile([]);
  assert.match(file, /# Learned skills \(0\)/);
  assert.match(file, /No procedural lessons/);
});
